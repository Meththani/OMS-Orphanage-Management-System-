export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      return localStorage.getItem('language') || 'en';
    } catch (e) {
      return 'en';
    }
  });

  const setLanguage = (lang) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('language', lang);
    } catch (e) {
      console.warn('Could not save language to localStorage:', e);
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
    if (language === 'si') {
      document.body.classList.add('lang-si');
    } else {
      document.body.classList.remove('lang-si');
    }
  }, [language]);

  const t = (key, fallback) => {
    if (!key) return fallback || '';
    if (language === 'si') {
      const strKey = String(key).trim();
      const lowerKey = strKey.toLowerCase();
      const capKey = strKey.charAt(0).toUpperCase() + strKey.slice(1);

      return translations[strKey] ||
             translations[lowerKey] ||
             translations[capKey] ||
             fallback ||
             strKey;
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
